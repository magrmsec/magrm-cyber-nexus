export function getToolDetails(tool: Tool): ToolDetails {
  const profile = categoryProfiles[tool.category] ?? fallbackProfile;
  return {
    overview: `${tool.name} هي ${tool.description.replace(/[.!؟]+$/, "")}. ضمن هذا المسار تُستخدم ${profile.focus}`,
    capabilities: [
      `تحليل المهمة المرتبطة بـ ${tool.name} وتحديد نطاقها قبل البدء`,
      ...profile.uses,
    ],
    useCases: profile.uses,
    deliverables: profile.deliverables,
  };
}
